import * as React from "react"
import { Menu as ContextMenuPrimitive } from "@base-ui/react/menu"
import { cn } from "cn"
import { ChevronRightIcon, CheckIcon } from "lucide-react"

type ContextMenuPosition = {
  x: number
  y: number
}

type ContextMenuContextValue = {
  anchor: {
    getBoundingClientRect: () => DOMRect
  }
  openAt: (position: ContextMenuPosition) => void
}

const ContextMenuContext = React.createContext<ContextMenuContextValue | null>(
  null
)

function useContextMenu() {
  const context = React.useContext(ContextMenuContext)

  if (!context) {
    throw new Error("Context menu components must be inside ContextMenu.")
  }

  return context
}

function ContextMenu({ children }: { children: React.ReactNode }) {
  const [open, setOpen] = React.useState(false)
  const [position, setPosition] = React.useState<ContextMenuPosition>({
    x: 0,
    y: 0,
  })
  const anchor = React.useMemo(
    () => ({
      getBoundingClientRect: () =>
        new DOMRect(position.x, position.y, 0, 0),
    }),
    [position]
  )
  const openAt = React.useCallback((nextPosition: ContextMenuPosition) => {
    setPosition(nextPosition)
    setOpen(true)
  }, [])
  const contextValue = React.useMemo(
    () => ({ anchor, openAt }),
    [anchor, openAt]
  )

  return (
    <ContextMenuPrimitive.Root
      data-slot="context-menu"
      open={open}
      onOpenChange={setOpen}
      modal={false}
    >
      <ContextMenuContext.Provider value={contextValue}>
        {children}
      </ContextMenuContext.Provider>
    </ContextMenuPrimitive.Root>
  )
}

function ContextMenuPortal({ ...props }: ContextMenuPrimitive.Portal.Props) {
  return (
    <ContextMenuPrimitive.Portal data-slot="context-menu-portal" {...props} />
  )
}

type ContextMenuTriggerProps = React.ComponentPropsWithoutRef<"div"> & {
  render?: React.ReactElement<React.HTMLAttributes<HTMLDivElement>>
}

function ContextMenuTrigger({
  className,
  onContextMenu,
  render,
  children,
  ...props
}: ContextMenuTriggerProps) {
  const { openAt } = useContextMenu()

  function handleContextMenu(event: React.MouseEvent<HTMLDivElement>) {
    onContextMenu?.(event)

    if (!event.defaultPrevented) {
      event.preventDefault()
      openAt({ x: event.clientX, y: event.clientY })
    }
  }

  const triggerClassName = cn("select-none", className)

  if (render) {
    return React.cloneElement(
      render,
      {
        ...props,
        className: cn(render.props.className, triggerClassName),
        onContextMenu: handleContextMenu,
      },
      children
    )
  }

  return (
    <div
      {...props}
      data-slot="context-menu-trigger"
      className={triggerClassName}
      onContextMenu={handleContextMenu}
    >
      {children}
    </div>
  )
}

function ContextMenuContent({
  className,
  align = "start",
  alignOffset = 4,
  side = "right",
  sideOffset = 0,
  ...props
}: ContextMenuPrimitive.Popup.Props &
  Pick<
    ContextMenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  >) {
  const { anchor } = useContextMenu()

  return (
    <ContextMenuPrimitive.Portal>
      <ContextMenuPrimitive.Positioner
        anchor={anchor}
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <ContextMenuPrimitive.Popup
          data-slot="context-menu-content"
          className={cn(
            "z-50 max-h-(--available-height) min-w-36 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover p-1 text-popover-foreground shadow-md outline-none",
            className
          )}
          {...props}
        />
      </ContextMenuPrimitive.Positioner>
    </ContextMenuPrimitive.Portal>
  )
}

